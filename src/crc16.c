uint16_t crc16(const char *buf, int len) {
    int counter = 0;
    uint16_t crc = 0;

    for(; counter + 2 < len; counter += 3) {
        /* explicitly get two bytes */
        uint16_t a = (uint8_t)buf[counter];
        uint16_t b = (uint8_t)buf[counter + 1];
        uint16_t c = (uint8_t)buf[counter + 2];

        uint16_t lut1 = crc16tab[0 * 256 + (uint8_t)(c)];
        uint16_t lut2 = crc16tab[1 * 256 + (uint8_t)(b ^ crc)];
        uint16_t lut3 = crc16tab[2 * 256 + (uint8_t)(a ^ (crc >> 8))];
        crc = lut1 ^ lut2 ^ lut3;
    }

    for(; counter + 1 < len; counter += 2) {
        /* explicitly get two bytes */
        uint16_t a = (uint8_t)buf[counter];
        uint16_t b = (uint8_t)buf[counter + 1];
        uint16_t tmp = ((a << 8) | b);

        crc ^= tmp;
        // fit LITTLE-ENDIAN architecture
        crc = crc16tab[1 * 256 + (uint8_t)(crc >> 8)] ^ crc16tab[0 * 256 + (uint8_t)(crc >> 0)];
    }

    // deal with leftover
    for(; counter < len; counter++)
        crc = (crc << 8) ^ crc16tab[((crc >> 8) ^ (uint8_t)buf[counter]) & 0x00FF];
    return crc;
}
